-- ZCredit giveaways
-- Run once in the Supabase SQL Editor (safe to re-run).
--
-- How it works:
--   * The admin creates a giveaway (amount per person, start time, expiry, optional spot limit).
--   * Each giveaway gets a random code -> link:  index.html?giveaway=<code>
--   * Users claim through claim_giveaway(), which runs on the server side of the database:
--     it checks the time window, spot limit and "one claim per user" under a row lock, then
--     credits the balance and logs a transaction in a single atomic step.
--   * The browser can never credit money itself, and the giveaways table is admin-only, so
--     codes can't be enumerated.

-- Single place that defines who the admin is (same account as the other admin policies).
create or replace function public.is_zcredit_admin()
returns boolean language sql stable as $$
  select auth.uid() = '5f65415b-a349-4f73-8bcd-8f0f82aeebd9'::uuid
$$;

-- ───────────── Tables ─────────────
create table if not exists public.giveaways (
  id          bigint generated by default as identity primary key,
  code        text not null unique default left(replace(gen_random_uuid()::text, '-', ''), 16),
  amount      numeric(12,2) not null check (amount > 0),         -- paid to EACH person who claims
  max_claims  integer check (max_claims is null or max_claims > 0), -- null = unlimited until expiry
  starts_at   timestamptz not null default now(),                 -- future date = scheduled
  expires_at  timestamptz not null,
  cancelled   boolean not null default false,
  created_at  timestamptz not null default now(),
  check (expires_at > starts_at)
);

create table if not exists public.giveaway_claims (
  id           bigint generated by default as identity primary key,
  giveaway_id  bigint not null references public.giveaways(id) on delete cascade,
  user_id      uuid   not null references public.profiles(id) on delete cascade,
  amount       numeric(12,2) not null,
  claimed_at   timestamptz not null default now(),
  unique (giveaway_id, user_id)                                   -- one claim per person, enforced by the DB
);
create index if not exists giveaway_claims_giveaway_idx on public.giveaway_claims (giveaway_id);

-- ───────────── Row level security ─────────────
alter table public.giveaways enable row level security;
alter table public.giveaway_claims enable row level security;

drop policy if exists "giveaways_admin_all" on public.giveaways;
create policy "giveaways_admin_all" on public.giveaways
for all to authenticated
using (public.is_zcredit_admin()) with check (public.is_zcredit_admin());

drop policy if exists "giveaway_claims_admin_select" on public.giveaway_claims;
create policy "giveaway_claims_admin_select" on public.giveaway_claims
for select to authenticated using (public.is_zcredit_admin());

drop policy if exists "giveaway_claims_select_own" on public.giveaway_claims;
create policy "giveaway_claims_select_own" on public.giveaway_claims
for select to authenticated using (user_id = auth.uid());
-- No insert/update/delete policies on claims: only claim_giveaway() can write them.

-- ───────────── Public lookup (so a link can show its details before login) ─────────────
create or replace function public.get_giveaway(p_code text)
returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare
  g   giveaways%rowtype;
  n   integer;
  st  text;
  uid uuid := auth.uid();
begin
  select * into g from giveaways where code = p_code;
  if not found then
    return jsonb_build_object('found', false);
  end if;

  select count(*) into n from giveaway_claims where giveaway_id = g.id;

  st := case
    when g.cancelled then 'cancelled'
    when now() < g.starts_at then 'scheduled'
    when now() >= g.expires_at then 'expired'
    when g.max_claims is not null and n >= g.max_claims then 'full'
    else 'active'
  end;

  return jsonb_build_object(
    'found', true,
    'status', st,
    'amount', g.amount,
    'starts_at', g.starts_at,
    'expires_at', g.expires_at,
    'spots_left', case when g.max_claims is null then null else greatest(g.max_claims - n, 0) end,
    'already_claimed', uid is not null and exists (
      select 1 from giveaway_claims where giveaway_id = g.id and user_id = uid),
    'server_now', now()
  );
end $$;

-- ───────────── Claim (atomic) ─────────────
create or replace function public.claim_giveaway(p_code text)
returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  g   giveaways%rowtype;
  n   integer;
  uid uuid := auth.uid();
begin
  if uid is null then
    return jsonb_build_object('ok', false, 'error', 'Log in to claim this giveaway.');
  end if;

  -- Row lock: simultaneous claims on the same giveaway are processed one at a time,
  -- so the spot limit can never be exceeded.
  select * into g from giveaways where code = p_code for update;
  if not found then
    return jsonb_build_object('ok', false, 'error', 'This giveaway link is not valid.');
  end if;
  if g.cancelled then
    return jsonb_build_object('ok', false, 'error', 'This giveaway was cancelled.');
  end if;
  if now() < g.starts_at then
    return jsonb_build_object('ok', false, 'error', 'This giveaway has not started yet.');
  end if;
  if now() >= g.expires_at then
    return jsonb_build_object('ok', false, 'error', 'This giveaway has expired.');
  end if;
  if exists (select 1 from giveaway_claims where giveaway_id = g.id and user_id = uid) then
    return jsonb_build_object('ok', false, 'error', 'You already claimed this giveaway.');
  end if;
  if g.max_claims is not null then
    select count(*) into n from giveaway_claims where giveaway_id = g.id;
    if n >= g.max_claims then
      return jsonb_build_object('ok', false, 'error', 'All spots for this giveaway have been claimed.');
    end if;
  end if;

  -- Flag read by the optional balance-lock trigger (supabase-lock-balance.sql).
  perform set_config('zcredit.allow_balance_change', 'on', true);
  update profiles set balance = balance + g.amount where id = uid;
  if not found then
    return jsonb_build_object('ok', false, 'error', 'Your account profile was not found.');
  end if;
  perform set_config('zcredit.allow_balance_change', 'off', true);

  insert into giveaway_claims (giveaway_id, user_id, amount) values (g.id, uid, g.amount);
  insert into transactions (user_id, type, title, amount) values (uid, 'deposit', 'Giveaway', g.amount);

  return jsonb_build_object('ok', true, 'amount', g.amount);
end $$;

-- Lock down who may call them. (Supabase grants new functions to anon by default, so revoke it.)
revoke all on function public.claim_giveaway(text) from public, anon;
grant execute on function public.claim_giveaway(text) to authenticated;
revoke all on function public.get_giveaway(text) from public;
grant execute on function public.get_giveaway(text) to anon, authenticated;

-- ───────────── Realtime (admin sees claim counts update live) ─────────────
do $$ begin
  alter publication supabase_realtime add table public.giveaways;
exception when duplicate_object then null;
end $$;
do $$ begin
  alter publication supabase_realtime add table public.giveaway_claims;
exception when duplicate_object then null;
end $$;
